// Custom Worker entry, wrapping the one OpenNext generates (OpenNext's documented
// "custom worker" pattern). wrangler.jsonc points `main` here.
//
// Why: OpenNext's /_next/image handler (@opennextjs/cloudflare 1.20.x) only sets
// Cache-Control when the source is "immutable" (/_next/static/media, or a source
// whose own Cache-Control says immutable). Our photos are plain /images/*.png, so
// resized images went out with no Cache-Control at all and every repeat visit
// re-ran the Worker and a Cloudflare Images transform. next.config's
// images.minimumCacheTTL is compiled in but never read by that handler.
//
// Not `immutable`: /images/* filenames are not content-hashed, so a replaced
// photo must still show up within a day. Vary: Accept is left as OpenNext set it.

// .open-next/ is generated by `opennextjs-cloudflare build` and absent on a clean
// checkout, so the import may or may not resolve for tsc; @ts-ignore covers both.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore
import handler from "./.open-next/worker.js";

const IMAGE_CACHE_CONTROL = "public, max-age=86400, stale-while-revalidate=604800";

const worker = {
  async fetch(request: Request, env: unknown, ctx: unknown): Promise<Response> {
    const response: Response = await handler.fetch(request, env, ctx);

    if (
      response.status === 200 &&
      new URL(request.url).pathname.startsWith("/_next/image") &&
      !response.headers.has("Cache-Control")
    ) {
      const cached = new Response(response.body, response);
      cached.headers.set("Cache-Control", IMAGE_CACHE_CONTROL);
      return cached;
    }

    return response;
  },
};

export default worker;

